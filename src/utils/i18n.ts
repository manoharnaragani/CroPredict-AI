export function getCropDisplayName(cropId: string, lang: LanguageCode = 'en'): string {
  if (lang === 'en') return cropId;
  const match = CROP_TRANSLATIONS[cropId];
  if (match && match[lang]) {
    return `${match[lang]} (${cropId})`;
  }
  return cropId;
}

export function getSeasonDisplayName(season: string, lang: LanguageCode = 'en'): string {
  if (lang === 'en') return season;
  if (season === 'Kharif') {
    if (lang === 'hi' || lang === 'mr' || lang === 'gu') return 'खरीफ (मानसून)';
    if (lang === 'bn') return 'খরিফ (বর্ষাকালীন)';
    if (lang === 'te') return 'ఖరీఫ్ (వర్షాకాలం)';
    if (lang === 'ta') return 'காரிஃப் (மழைக்காலம்)';
    if (lang === 'kn') return 'ಖಾರೀಫ್ (ಮುಂಗಾರು)';
  }
  if (season === 'Rabi') {
    if (lang === 'hi' || lang === 'mr' || lang === 'gu') return 'रबी (शीतकालीन)';
    if (lang === 'bn') return 'রবি (শীতকালীন)';
    if (lang === 'te') return 'రబీ (శీతాకాలం)';
    if (lang === 'ta') return 'ரபி (குளிர்காலம்)';
    if (lang === 'kn') return 'ರಬಿ (ಹಿಂಗಾರು)';
  }
  if (season === 'Summer' || season === 'Zaid') {
    if (lang === 'hi' || lang === 'mr') return 'जायદ (ग्रीष्मकालीन)';
    if (lang === 'te') return 'ఎండకాలం (జైద్)';
    if (lang === 'kn') return 'ಬೇಸಿಗೆ (ಜೈದ್)';
  }
  return season;
}

/**
 * Language coverage diagnostic helper to check every language for missing keys
 */
export function getLanguageCoverageReport(): Record<
  LanguageCode,
  { totalKeys: number; translatedKeys: number; missingKeys: string[]; coveragePct: number }
> {
  const allKeys = Object.keys(ENGLISH_TRANSLATIONS) as (keyof TranslationDictionary)[];
  const report: any = {};

  for (const lang of SCHEDULED_LANGUAGES) {
    const code = lang.code;
    const dict = TRANSLATIONS_MAP[code] || {};
    const missing: string[] = [];
    let translatedCount = 0;

    for (const key of allKeys) {
      if (dict[key] && dict[key] !== '') {
        // In English, it matches. In other languages, if it's equal to English, it fell back.
        if (code === 'en' || dict[key] !== ENGLISH_TRANSLATIONS[key] || key === 'appName') {
          translatedCount++;
        } else {
          missing.push(key);
        }
      } else {
        missing.push(key);
      }
    }

    report[code] = {
      totalKeys: allKeys.length,
      translatedKeys: translatedCount,
      missingKeys: missing,
      coveragePct: Math.round((translatedCount / allKeys.length) * 100),
    };
  }

  return report;
}

export function registerRegionalLanguage(
  option: LanguageOption,
  dictionary: Partial<TranslationDictionary>
): void {
  if (!SCHEDULED_LANGUAGES.some(l => l.code === option.code)) {
    SCHEDULED_LANGUAGES.push(option);
  }
  TRANSLATIONS_MAP[option.code] = {
    ...ENGLISH_TRANSLATIONS,
    ...dictionary,
    appName: 'CroPredict AI',
  };
}
