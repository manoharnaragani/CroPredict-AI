export const LOCAL_STORAGE_KEY_LANGUAGE = 'cropredict_language';
export const LOCAL_STORAGE_KEY_THEME = 'cropredict_theme';

export function getStoredLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY_LANGUAGE) as LanguageCode;
    if (saved && SCHEDULED_LANGUAGES.some(l => l.code === saved)) {
      return saved;
    }
  } catch {
    // fallback
  }
  return 'en'; // Default to English on first visit
}

export function saveStoredLanguage(lang: LanguageCode): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY_LANGUAGE, lang);
  } catch {
    // ignore
  }
}

/**
 * Translation helper with strict English fallback and invariant branding
 */
export function t(key: keyof TranslationDictionary, lang: LanguageCode = 'en'): string {
  // Exact branding in every language
  if (key === 'appName') return 'CroPredict AI';

  const langDict = TRANSLATIONS_MAP[lang];
  if (langDict && langDict[key]) {
    return langDict[key]!;
  }
  return ENGLISH_TRANSLATIONS[key] || '';
}

